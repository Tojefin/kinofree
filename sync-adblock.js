// Генерирует платформенные списки блокировки рекламы из единого источника:
//   adblock-config.json (корень репозитория)
//
// Цели генерации:
//   - src-tauri/tauri.conf.json — секция --host-rules в additionalBrowserArgs (desktop/WebView2)
//   - src-tauri/gen/android/app/src/main/java/su/kinofree/app/AdDomains.kt (android-прокси)
//
// Использование:
//   node sync-adblock.js           # перезаписать сгенерированные файлы
//   node sync-adblock.js --check   # не писать; exit 1, если файлы устарели (используется в CI)
//   npm run sync-adblock
//   npm run sync-adblock:check

import { existsSync, readFileSync, writeFileSync } from 'fs';

const check = process.argv.includes('--check');

const CONFIG_PATH = 'adblock-config.json';
const TAURI_CONF_PATH = 'src-tauri/tauri.conf.json';
const AD_DOMAINS_KT_PATH = 'src-tauri/gen/android/app/src/main/java/su/kinofree/app/AdDomains.kt';

const HOST_RULES_RE = /--host-rules="[^"]*"/;
const DOMAIN_RE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

// BOM (который любят добавлять Windows-редакторы) ломает JSON.parse — срезаем его
const read = (path) => readFileSync(path, 'utf8').replace(/^\uFEFF/, '');
const fail = (message) => {
	console.error(message);
	process.exit(1);
};

// --- единый источник: adblock-config.json ---

if (!existsSync(CONFIG_PATH)) fail(`Не найден ${CONFIG_PATH}`);

let config;
try {
	config = JSON.parse(read(CONFIG_PATH));
} catch {
	fail(`${CONFIG_PATH}: некорректный JSON`);
}

if (!Array.isArray(config.domains) || config.domains.length === 0) {
	fail(`${CONFIG_PATH}: поле domains должно быть непустым массивом строк`);
}

const domains = [];
for (const entry of config.domains) {
	const domain = String(entry).trim().toLowerCase();
	if (!DOMAIN_RE.test(domain)) fail(`${CONFIG_PATH}: некорректный домен "${entry}"`);
	if (!domains.includes(domain)) domains.push(domain);
}

// --- desktop: --host-rules в src-tauri/tauri.conf.json ---
// На каждый домен две маски: точный хост и поддомены — те же семантики,
// что у isBlocked() в android-прокси (host == it || host.endsWith(".$it")).

const hostRules = domains.flatMap((d) => [`MAP ${d} ~NOTFOUND`, `MAP *.${d} ~NOTFOUND`]).join(',');

const conf = JSON.parse(read(TAURI_CONF_PATH));
const browserArgs = conf.app?.windows?.[0]?.additionalBrowserArgs;
if (typeof browserArgs !== 'string') {
	fail(`${TAURI_CONF_PATH}: не найден app.windows[0].additionalBrowserArgs`);
}
conf.app.windows[0].additionalBrowserArgs = HOST_RULES_RE.test(browserArgs)
	? browserArgs.replace(HOST_RULES_RE, `--host-rules="${hostRules}"`)
	: `${browserArgs.trimEnd()} --host-rules="${hostRules}"`;
const tauriText = JSON.stringify(conf, null, 2) + '\n';

// --- android: AdDomains.kt ---

const ktList = domains.map((d) => `    "${d}"`).join(',\n');
const ktText = `// @generated by sync-adblock.js — не редактировать вручную.
// Единый источник: ${CONFIG_PATH} (корень репозитория).

package su.kinofree.app

/**
 * Список рекламных доменов для блокировки.
 *
 * Desktop: те же домены попадают в --host-rules (src-tauri/tauri.conf.json).
 * Android: список использует локальный прокси AdBlockProxy (MainActivity.kt).
 */
internal object AdDomains {
  val ALL = listOf(
${ktList}
  )
}
`;

// --- запись / проверка ---
// Переводы строк сохраняются как в текущем файле (CRLF-чекаут на Windows не должен
// ломать --check); сравниваем побайтово с учётом этого.

const targets = [
	{ path: TAURI_CONF_PATH, text: tauriText },
	{ path: AD_DOMAINS_KT_PATH, text: ktText }
];

const stale = [];
for (const target of targets) {
	const existing = existsSync(target.path) ? read(target.path) : null;
	const nl = existing !== null && existing.includes('\r\n') ? '\r\n' : '\n';
	target.next = target.text.replace(/\n/g, nl);
	if (existing !== target.next) stale.push(target);
}

if (stale.length === 0) {
	console.log(`Списки блокировки синхронизированы с ${CONFIG_PATH} (${domains.length} доменов).`);
	process.exit(0);
}

if (check) {
	console.error(`Сгенерированные списки блокировки устарели относительно ${CONFIG_PATH}:`);
	for (const { path } of stale) console.error(`  ${path}`);
	console.error('Запустите: npm run sync-adblock');
	process.exit(1);
}

for (const { path, next } of stale) {
	writeFileSync(path, next);
	console.log(`обновлён ${path}`);
}
console.log(`Готово: ${domains.length} доменов из ${CONFIG_PATH}.`);
